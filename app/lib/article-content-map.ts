/**
 * 根据文章标题获取对应的内容
 */
export function getContentByTitle(title: string): string | null {
  return ARTICLE_CONTENT_MAP[title] || null;
}

/**
 * 增强版文章获取函数，优先使用映射内容
 */
export function getArticleWithContent(article: RSWEntry): RSWEntry {
  // 如果文章已有内容，直接返回
  if (article.content) {
    return article;
  }

  // 尝试从映射中获取内容
  const mappedContent = getContentByTitle(article.title);
  if (mappedContent) {
    return {
      ...article,
      content: mappedContent
    };
  }

  // 如果没有映射内容，返回原文章
  return article;
}